import SwiftUI

extension Font {
    static func signikaSC(size: CGFloat) -> Font {
        return .custom("SignikaSC-Regular", size: size)
    }
    
    static func signikaSCBold(size: CGFloat) -> Font {
        return .custom("SignikaSC-Bold", size: size)
    }
    
    static func signikaSCSemiBold(size: CGFloat) -> Font {
        return .custom("SignikaSC-SemiBold", size: size)
    }
    
    static func signikaLight(size: CGFloat) -> Font {
        return .custom("Signika-Light", size: size)
    }
    
    static func signikaRegular(size: CGFloat) -> Font {
        return .custom("Signika-Regular", size: size)
    }
    
    static func signikaMedium(size: CGFloat) -> Font {
        return .custom("Signika-Medium", size: size)
    }
    
    static func signikaSemiBold(size: CGFloat) -> Font {
        return .custom("Signika-SemiBold", size: size)
    }
    
    static func signikaBold(size: CGFloat) -> Font {
        return .custom("Signika-Bold", size: size)
    }
}


